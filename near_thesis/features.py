"""Derive tidy metric tables from raw snapshots. Output: data/derived/*.csv (+ parquet where large).

Tables
- daily.csv      one row per day (2020-07 -> today): NEAR activity, fees, price, Intents volume/fees, TVL, stablecoins
- monthly.csv    month aggregates (sums for flows, means for stocks) + derived ratios
- yearly.csv     yearly averages used in THESIS.md headline tables
- peers.csv      latest 30d panel: DEX volume, fees, TVL, stablecoins, market cap per chain
- developer.csv  weekly commits per core repo
Every column has a definition in docs/METRICS.md (generated by `make thesis`).
"""
from __future__ import annotations

from datetime import datetime, timezone

import numpy as np
import pandas as pd

from .config import DERIVED, START_DATE
from .fetch import PEER_CHAINS, PEER_GECKO
from .http import load_raw

YOCTO = 1e24


def _num(s: pd.Series) -> pd.Series:
    return pd.to_numeric(s, errors="coerce")


def nearblocks_daily() -> pd.DataFrame:
    rows = load_raw("nearblocks_charts")["data"]
    df = pd.DataFrame(rows)
    df["date"] = pd.to_datetime(df["date"]).dt.tz_localize(None).dt.normalize()
    out = pd.DataFrame({
        "date": df["date"],
        "txns": _num(df["txns"]),
        "active_accounts": _num(df["active_accounts"]),
        "new_accounts": _num(df["new_accounts"]),
        "active_contracts": _num(df["active_contracts"]),
        "new_contracts": _num(df["new_contracts"]),
        "blocks": _num(df["blocks"]),
        "gas_used_tgas": _num(df["gas_used"]) / 1e12,
        "tx_fee_near": _num(df["txn_fee"]) / YOCTO,
        "tx_fee_usd": _num(df["txn_fee_usd"]),
        "tx_volume_near": _num(df["txn_volume"]) / YOCTO,
        "tx_volume_usd": _num(df["txn_volume_usd"]),
        "near_price": _num(df["near_price"]).replace(0, np.nan),
        "market_cap_usd": _num(df["market_cap"]).replace(0, np.nan),
        "circulating_supply": _num(df["circulating_supply"]) / YOCTO,
    })
    return out.sort_values("date").reset_index(drop=True)


def _llama_chart(name: str, key: str = "totalDataChart") -> pd.Series:
    d = load_raw(name)["data"]
    pts = d[key]
    s = pd.Series({pd.Timestamp(int(t), unit="s"): float(v) for t, v in pts if v is not None})
    return s.sort_index()


def _llama_tvl(chain: str) -> pd.Series:
    d = load_raw(f"llama_tvl_{chain}")["data"]
    return pd.Series({pd.Timestamp(int(p["date"]), unit="s"): float(p["tvl"]) for p in d}).sort_index()


def _llama_stables(chain: str) -> pd.Series:
    d = load_raw(f"llama_stables_{chain}")["data"]
    return pd.Series({pd.Timestamp(int(p["date"]), unit="s"): float(p["totalCirculatingUSD"]["peggedUSD"])
                      for p in d if p.get("totalCirculatingUSD")}).sort_index()


def _price(cid: str) -> pd.Series:
    d = load_raw(f"price_{cid}")["data"]
    s = pd.Series({pd.Timestamp(int(t), unit="s").normalize(): float(p) for t, p in d})
    return s[~s.index.duplicated(keep="last")].sort_index()


def build_daily() -> pd.DataFrame:
    nb = nearblocks_daily().set_index("date")
    nb["intents_volume_usd"] = _llama_chart("llama_intents_volume")
    nb["intents_fees_usd"] = _llama_chart("llama_intents_fees")
    nb["near_dex_volume_usd"] = _llama_chart("llama_dexs_near")
    nb["near_app_fees_usd"] = _llama_chart("llama_fees_near")      # DefiLlama "fees" = app-level fees on NEAR (Intents dominates)
    nb["tvl_usd"] = _llama_tvl("near")
    nb["stablecoins_usd"] = _llama_stables("near")
    for cid in ["near", "bitcoin", "ethereum"]:
        nb[f"price_{cid}"] = _price(cid)
    nb = nb.loc[nb.index >= pd.Timestamp(START_DATE)]
    # value-weighted and quality-ish ratios used throughout
    nb["usd_per_txn"] = nb["tx_volume_usd"] / nb["txns"]
    nb["fee_usd_per_active_account"] = nb["tx_fee_usd"] / nb["active_accounts"]
    nb["intents_share_of_near_dex"] = nb["intents_volume_usd"] / nb["near_dex_volume_usd"]
    nb["intents_volume_to_tvl"] = nb["intents_volume_usd"] / nb["tvl_usd"]
    nb.index.name = "date"
    return nb.reset_index()


def build_monthly(daily: pd.DataFrame) -> pd.DataFrame:
    d = daily.set_index("date")
    sums = ["txns", "new_accounts", "tx_fee_usd", "tx_volume_usd", "intents_volume_usd", "intents_fees_usd",
            "near_dex_volume_usd", "near_app_fees_usd", "tx_fee_near"]
    means = ["active_accounts", "active_contracts", "near_price", "market_cap_usd", "tvl_usd", "stablecoins_usd",
             "usd_per_txn", "price_near", "price_bitcoin", "price_ethereum"]
    m = pd.concat([d[sums].resample("MS").sum(min_count=1), d[means].resample("MS").mean()], axis=1)
    m["days"] = d["txns"].resample("MS").count()
    m["fees_to_mcap_annualized"] = (m["tx_fee_usd"] * 12) / m["market_cap_usd"]
    m["app_fees_to_mcap_annualized"] = (m["near_app_fees_usd"] * 12) / m["market_cap_usd"]
    m["intents_volume_to_stables"] = m["intents_volume_usd"] / m["stablecoins_usd"]
    m.index.name = "month"
    return m.reset_index()


def build_yearly(daily: pd.DataFrame) -> pd.DataFrame:
    d = daily.set_index("date")
    cols = ["txns", "active_accounts", "new_accounts", "tx_fee_usd", "tx_volume_usd", "usd_per_txn", "near_price",
            "intents_volume_usd", "tvl_usd", "stablecoins_usd"]
    y = d[cols].resample("YS").mean()
    y["days"] = d["txns"].resample("YS").count()
    y.index = y.index.year
    y.index.name = "year"
    return y.reset_index()


def build_peers() -> pd.DataFrame:
    chains = {c["name"]: c for c in load_raw("llama_chains")["data"]}
    markets = {m["id"]: m for m in load_raw("gecko_peer_markets")["data"]}
    rows = []
    for c in PEER_CHAINS:
        name = {"near": "Near", "solana": "Solana", "base": "Base", "arbitrum": "Arbitrum", "polygon": "Polygon",
                "avalanche": "Avalanche", "sui": "Sui", "aptos": "Aptos"}[c]
        dex = load_raw(f"llama_dexs_{c}")["data"]
        fees = load_raw(f"llama_fees_{c}")["data"]
        st = _llama_stables(c)
        gid = PEER_GECKO[c]
        mcap = markets.get(gid, {}).get("market_cap") if gid else None
        rows.append({"chain": name, "tvl_usd": chains.get(name, {}).get("tvl"),
                     "dex_volume_30d_usd": dex.get("total30d"), "app_fees_30d_usd": fees.get("total30d"),
                     "stablecoins_usd": float(st.iloc[-1]) if len(st) else None, "market_cap_usd": mcap,
                     "has_native_token": gid is not None})
    p = pd.DataFrame(rows)
    p["dex_volume_to_tvl_30d"] = p["dex_volume_30d_usd"] / p["tvl_usd"]
    p["fees_to_mcap_annualized"] = (p["app_fees_30d_usd"] * 12) / p["market_cap_usd"]
    p["stables_to_tvl"] = p["stablecoins_usd"] / p["tvl_usd"]
    return p


def build_developer() -> pd.DataFrame:
    d = load_raw("github_commit_activity")["data"]
    rows = []
    for repo, weeks in d.items():
        for w in weeks:
            rows.append({"repo": repo, "week": pd.Timestamp(int(w["week"]), unit="s"), "commits": int(w["total"])})
    return pd.DataFrame(rows).sort_values(["repo", "week"]) if rows else pd.DataFrame(columns=["repo", "week", "commits"])


def run() -> None:
    daily = build_daily()
    daily.to_csv(DERIVED / "daily.csv", index=False)
    monthly = build_monthly(daily)
    monthly.to_csv(DERIVED / "monthly.csv", index=False)
    build_yearly(daily).to_csv(DERIVED / "yearly.csv", index=False)
    build_peers().to_csv(DERIVED / "peers.csv", index=False)
    build_developer().to_csv(DERIVED / "developer.csv", index=False)
    (DERIVED / "features_built_at.txt").write_text(datetime.now(timezone.utc).isoformat(timespec="seconds"))
    print(f"daily: {len(daily):,} rows {daily['date'].min().date()} -> {daily['date'].max().date()}")
    print(f"monthly: {len(monthly):,} rows; peers: {len(PEER_CHAINS)} chains")
