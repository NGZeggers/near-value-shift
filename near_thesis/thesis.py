"""Generate THESIS.md, docs/REPRODUCIBILITY.md and docs/METRICS.md from pipeline outputs. No hand-typed numbers."""
from __future__ import annotations

import json
import pandas as pd

from .config import DERIVED, DOCS, MODELS, ROOT
from .http import raw_manifest


def usd(v, d=1):
    if v is None or pd.isna(v):
        return "n/a"
    a = abs(v)
    if a >= 1e9: return f"${v/1e9:.{d}f}B"
    if a >= 1e6: return f"${v/1e6:.{d}f}M"
    if a >= 1e3: return f"${v/1e3:.{d}f}K"
    return f"${v:.2f}"


def num(v, d=0):
    return "n/a" if v is None or pd.isna(v) else f"{v:,.{d}f}"


def pct(a, b):
    return "n/a" if not b or pd.isna(a) or pd.isna(b) else f"{(a/b-1)*100:+.0f}%"


def load():
    d = pd.read_csv(DERIVED / "daily.csv", parse_dates=["date"]).set_index("date")
    m = pd.read_csv(DERIVED / "monthly.csv", parse_dates=["month"]).set_index("month")
    y = pd.read_csv(DERIVED / "yearly.csv").set_index("year")
    peers = pd.read_csv(DERIVED / "peers.csv").set_index("chain")
    J = lambda n: json.loads((MODELS / n).read_text())
    return d, m, y, peers, J("breaks.json"), J("var_granger.json"), J("johansen.json"), J("signal_ic.json"), J("peer_valuation.json"), J("scenarios.json"), J("qaa_status.json"), J("intents_status.json"), pd.read_csv(MODELS / "yearly_corr.csv").set_index("year")


def build() -> str:
    d, m, y, peers, breaks, vg, jo, ic, pv, sc, qs, is_, yc = load()
    full = m[m.index < m.index.max()]
    last = full.iloc[-1]; last_m = str(full.index[-1].date())[:7]
    yoy = full.iloc[-13] if len(full) > 13 else full.iloc[0]
    first_i = m["intents_volume_usd"].replace(0, pd.NA).dropna()
    first_i_month, first_i_val = str(first_i.index[0].date())[:7], float(first_i.iloc[0])
    peak_aa = y["active_accounts"].idxmax(); cur_year = int(y.index.max())
    l90, p90 = d.iloc[-90:], d.iloc[-180:-90]
    g = {r["metric"]: r for r in vg if "usage_granger_causes_price" in r}
    ic12 = {r["metric"]: r for r in ic if r.get("horizon_weeks") == 12 and r.get("benchmark") == "btc" and "spearman_ic" in r}
    near_vel_rank, n_vel = pv["dex_volume_to_tvl_30d"]["near_rank"], pv["dex_volume_to_tvl_30d"]["n"]
    near_fee_rank, n_fee = pv["fees_to_mcap_annualized"]["near_rank"], pv["fees_to_mcap_annualized"]["n"]

    out = []
    out.append(f"# From clicks to settlement: an investment thesis on NEAR\n")
    out.append(f"Generated by `make thesis` from the snapshots in `data/` (data through {d.index.max().date()}). "
               "Every number below is produced by the pipeline; nothing is typed by hand. Interactive charts with their queries: `site/index.html`.\n")
    out.append("## The claim\n")
    out.append("NEAR's economic activity is shifting from high-count, low-value retail transactions (the 2024 mini-app era) to lower-count, "
               "higher-value cross-chain settlement through NEAR Intents. Raw activity metrics (transactions, active accounts) therefore "
               "understate the network, while value-weighted and quality-adjusted metrics show growth that is decoupled from the token price. "
               "The investable version of the claim: if value accrual to NEAR ever follows settlement volume rather than transaction count, "
               "the market is pricing the wrong metric.\n")
    out.append("Three falsifiable predictions were tested:\n")
    out.append("1. Intents volume and USD-denominated value flows rise while active accounts fall.\n"
               "2. The price-usage relationship weakens or flips after the 2025 regime change.\n"
               "3. Unique Intents users grow with volume (otherwise volume is a few market makers).\n")

    out.append("## Headline numbers\n")
    out.append("| Metric | " + " | ".join(str(i) for i in y.index) + " |\n|---|" + "---|" * len(y.index))
    for label, col, f in [("Transactions per day (avg)", "txns", num), ("Daily active accounts (avg)", "active_accounts", num),
                          ("New accounts per day (avg)", "new_accounts", num), ("USD moved per transaction (avg)", "usd_per_txn", lambda v: usd(v, 0)),
                          ("Gas fees burned per day (avg)", "tx_fee_usd", lambda v: usd(v, 1)), ("Intents volume per day (avg)", "intents_volume_usd", lambda v: usd(v, 1)),
                          ("TVL (avg)", "tvl_usd", lambda v: usd(v, 0)), ("NEAR price (avg)", "near_price", lambda v: f"${v:.2f}")]:
        out.append(f"| {label} | " + " | ".join(f(y.loc[i, col]) for i in y.index) + " |")
    out.append(f"\n{cur_year} covers {int(y.loc[cur_year, 'days'])} days.\n")

    out.append("## Evidence for\n")
    out.append(f"- **Settlement volume exploded while headcount collapsed.** NEAR Intents volume went from {usd(first_i_val)} in {first_i_month} to "
               f"{usd(last['intents_volume_usd'])} in {last_m} ({pct(last['intents_volume_usd'], yoy['intents_volume_usd'])} year over year). "
               f"Daily active accounts averaged {num(y.loc[peak_aa, 'active_accounts'])} in {peak_aa} and {num(last['active_accounts'])} in {last_m}.")
    out.append(f"- **Each transaction carries more value.** USD moved per transaction averaged {usd(y.loc[peak_aa, 'usd_per_txn'], 0)} in {peak_aa} and "
               f"{usd(last['usd_per_txn'], 0)} in {last_m}. Over the last 90 days vs the prior 90: transactions {pct(l90['txns'].mean(), p90['txns'].mean())}, "
               f"active accounts {pct(l90['active_accounts'].mean(), p90['active_accounts'].mean())}, USD transaction volume {pct(l90['tx_volume_usd'].mean(), p90['tx_volume_usd'].mean())}, "
               f"gas fees in USD {pct(l90['tx_fee_usd'].mean(), p90['tx_fee_usd'].mean())}.")
    out.append(f"- **Application fees dwarf protocol fees.** In {last_m}, application-level fees on NEAR (DefiLlama, dominated by Intents) were {usd(last['near_app_fees_usd'])} "
               f"against {usd(last['tx_fee_usd'])} of gas fees burned. The economic activity is real; it is just not captured by the protocol.")
    b_aa = breaks.get("active_accounts", {}).get("breaks", []); b_iv = breaks.get("intents_volume_usd", {}).get("breaks", [])
    out.append(f"- **The regime change is statistically detectable.** PELT structural-break detection on log daily active accounts finds breaks at "
               f"{', '.join(b_aa) if b_aa else 'none'}; on log Intents volume at {', '.join(b_iv) if b_iv else 'none'}.")
    c25 = yc.loc[2025, "intents_volume_usd"] if 2025 in yc.index and "intents_volume_usd" in yc.columns else None
    out.append(f"- **Price has not tracked the new activity.** Within-year correlation of log price with log Intents volume in 2025 was {num(c25, 2)}; "
               f"with log active accounts it was {num(yc.loc[2025, 'active_accounts'], 2)} in 2025 and {num(yc.loc[cur_year, 'active_accounts'], 2)} in {cur_year}.")
    out.append(f"- **Peers.** NEAR ranks {near_vel_rank} of {n_vel} on 30-day DEX volume divided by TVL (velocity): "
               f"{num(peers.loc['Near', 'dex_volume_to_tvl_30d'], 1)}x against {num(peers.loc['Solana', 'dex_volume_to_tvl_30d'], 1)}x for Solana.\n")

    out.append("## Evidence against\n")
    out.append(f"- **Value capture is weak.** NEAR ranks {near_fee_rank} of {n_fee} on annualized application fees divided by market cap "
               f"({num(peers.loc['Near', 'fees_to_mcap_annualized'] * 100, 2)}%). Intents fees go to solvers and the Intents protocol, not to NEAR holders; "
               f"market cap divided by trailing-12-month gas fees burned is {num(sc['inputs']['current_price_to_gas_fees'])}x.")
    out.append(f"- **Volume passes through, it does not stay.** Stablecoin supply on NEAR is {usd(d['stablecoins_usd'].dropna().iloc[-1])} and TVL is {usd(d['tvl_usd'].dropna().iloc[-1])}, "
               f"against {usd(last['intents_volume_usd'])} of monthly Intents volume. Stablecoins divided by TVL ranks {pv['stables_to_tvl']['near_rank']} of {pv['stables_to_tvl']['n']} among peers.")
    r = ic12.get("intents_volume_usd")
    if r:
        lo, hi = r["ci95_block_bootstrap"]
        out.append(f"- **Usage growth has not predicted returns.** The Spearman information coefficient between 4-week changes in Intents volume and 12-week "
                   f"forward NEAR returns in excess of BTC is {r['spearman_ic']:+.2f} (block-bootstrap 95% CI {lo:+.2f} to {hi:+.2f}, n={r['n']} weeks; "
                   f"first half {r['ic_first_half']:+.2f}, second half {r['ic_second_half']:+.2f}). If anything, faster Intents growth preceded weaker relative returns. "
                   "This is a short sample and the sign is unstable across halves.")
    gi = g.get("intents_volume_usd")
    if gi:
        out.append(f"- **No lead-lag found for Intents.** Granger tests on weekly log changes (lag {gi['lag_aic']} by AIC, n={gi['n_weeks']}): "
                   f"Intents volume to price p={gi['usage_granger_causes_price']['p_value']:.2f}, price to Intents volume p={gi['price_granger_causes_usage']['p_value']:.2f}. "
                   "Transactions and gas fees do show two-way Granger links with price (see table), consistent with price driving speculative activity rather than the reverse.")
    noj = [j["metric"] for j in jo if "cointegrated_5pct" in j and not j["cointegrated_5pct"]]
    out.append(f"- **No cointegration.** Johansen trace tests find no cointegrating relation at 5% between log price and {', '.join(noj) if noj else 'any usage metric'}.")
    out.append("- **The 2024 baseline is inflated.** A large share of 2024 activity was mini-app and airdrop traffic; a fall from an inflated base is "
               "not itself evidence of a shift to higher-value use. The quality-adjusted series (below) is the honest comparison.")
    out.append("- **The Intents volume series is third-party.** DefiLlama sources it from a Dune table maintained by the NEAR team. Our independent "
               "on-chain recomputation is the cross-check; where it is not computed, the volume figures above rest on one source.\n")

    out.append("## Quality-adjusted active accounts (L1)\n")
    if qs.get("computed"):
        q = pd.read_csv(MODELS / "qaa_monthly.csv", parse_dates=["month"]).set_index("month")
        pk = q["active_accounts_bq"].idxmax()
        src = qs.get("source", "bigquery")
        out.append((f"Source: {src}. " if src != "bigquery" else "") + ("In sampled mode the features are computed inside sampled block windows (see `data/blocks/sample_manifest.json`), the cluster shares are the estimate, and QAA = share x NearBlocks monthly active accounts. " if src != "bigquery" else "") +
                   f"Behavioral clustering ({qs.get('algorithm')}) of {num(qs.get('n'))} account-months. Clusters labeled as automation, mini-app farming, "
                   f"heavy unlabeled, human (multi-app), human (light) and Intents participants; QAA counts the last three. "
                   f"At the {str(pk.date())[:7]} peak QAA was {num(q.loc[pk, 'qaa'])} of {num(q.loc[pk, 'active_accounts_bq'])} active accounts "
                   f"({q.loc[pk, 'qaa_share']*100:.0f}%); in {str(q.index[-1].date())[:7]} it was {num(q.iloc[-1]['qaa'])} of {num(q.iloc[-1]['active_accounts_bq'])} "
                   f"({q.iloc[-1]['qaa_share']*100:.0f}%). Silhouette on a 20K sample: {num(qs.get('silhouette_sample'), 2)}.\n")
    else:
        out.append(f"Not computed: {qs.get('reason')} The SQL and the clustering code are in place (`sql/l1_*.sql`, `near_thesis/qaa.py`).\n")

    out.append("## Intents microstructure from raw events (L2)\n")
    if is_.get("computed"):
        im = pd.read_csv(MODELS / "intents_monthly.csv", parse_dates=["month"]).set_index("month")
        lm = im.iloc[-1]
        src = is_.get("source", "bigquery")
        out.append((f"Source: {src}; sampled counts and volumes are expanded to daily totals by blocks-in-day / blocks-sampled (users are an upper bound). " if src != "bigquery" else "") +
                   f"Parsed {num(is_['events'])} DIP-4 events on {is_['sampled_days']} sampled days; {is_['solver_accounts']} accounts classified as solvers "
                   f"(>= {is_['assumptions']['solver_min_batches_per_day']} batches and >= {is_['assumptions']['solver_min_counterparties']} counterparties in a day). "
                   f"Share of batches with a priced leg: {is_['priced_batch_share_mean']*100:.0f}%. In {str(im.index[-1].date())[:7]}: {num(lm['users_per_day'])} users per day, "
                   f"{num(lm['solvers_per_day'], 1)} solvers per day, solver HHI {lm['hhi_solver']:.2f}, top-1 solver share {lm['top1_solver_share']*100:.0f}%, "
                   f"median priced trade {usd(lm['median_trade_usd'])}. Independent monthly volume estimate {usd(lm['volume_est_usd'])} "
                   f"(95% day-bootstrap interval {usd(lm['volume_ci_lo'])} to {usd(lm['volume_ci_hi'])}) against DefiLlama {usd(m['intents_volume_usd'].loc[im.index[-1]])}.\n")
    else:
        out.append(f"Not computed: {is_.get('reason')} The event parser and the sampling design are in place (`sql/l2_intents_events.sql`, `near_thesis/intents.py`, `tests/test_intents.py`).\n")

    out.append("## Econometrics summary (L3)\n")
    out.append("| Metric | Weeks | Lag (AIC) | usage -> price p | price -> usage p | Johansen trace (cv 95%) |\n|---|---|---|---|---|---|")
    jmap = {j["metric"]: j for j in jo if "trace_r0" in j}
    for mname, r in g.items():
        j = jmap.get(mname, {})
        out.append(f"| {mname} | {r['n_weeks']} | {r['lag_aic']} | {r['usage_granger_causes_price']['p_value']:.3f} | {r['price_granger_causes_usage']['p_value']:.3f} | "
                   f"{j.get('trace_r0', float('nan')):.1f} ({j.get('cv95_r0', float('nan')):.1f}) |")
    out.append("\nWeekly means, log differences, VAR lag selected by AIC up to 8, F-test for Granger causality, Johansen with 2 lagged differences and no deterministic trend. "
               "Gas fees in USD correlate with price mechanically (fees are paid in NEAR); `tx_fee_near` is the activity measure in the signal tests.\n")

    out.append("## Signal tests (L4)\n")
    out.append("| Metric | IC 12w vs BTC | 95% CI | first half | second half | n |\n|---|---|---|---|---|---|")
    for mname, r in ic12.items():
        lo, hi = r["ci95_block_bootstrap"]
        out.append(f"| {mname} | {r['spearman_ic']:+.2f} | {lo:+.2f} to {hi:+.2f} | {r['ic_first_half']:+.2f} | {r['ic_second_half']:+.2f} | {r['n']} |")
    out.append("\nSignal: 4-week log change of the 4-week mean. Target: 12-week forward log return of NEAR minus BTC. Circular block bootstrap with 12-week blocks, 2,000 draws. "
               "With 20 tests at 5%, one spurious rejection is expected; treat single significant cells as suggestive.\n")

    out.append("## Scenarios, not forecasts (L4)\n")
    i = sc["inputs"]
    out.append(f"Trailing 12 months: Intents volume {usd(i['intents_volume_12m_usd'])}, Intents fees {usd(i['intents_fees_12m_usd'])} "
               f"(observed take rate {i['observed_take_rate_bps']:.1f} bps), gas fees burned {usd(i['gas_fees_12m_usd'])}, market cap {usd(i['market_cap_usd'])}. "
               f"Drawing {num(sc['n'])} scenarios with volume multiplier {sc['assumptions']['volume_multiplier']}, take rate {sc['assumptions']['take_rate_bps']}, "
               f"share accruing to the token {sc['assumptions']['share_to_token']}: median price-to-token-fees {num(sc['price_to_fees']['p50'])}x "
               f"(5th to 95th percentile {num(sc['price_to_fees']['p5'])}x to {num(sc['price_to_fees']['p95'])}x). {sc['assumptions']['note']}.\n")

    out.append("## What would change our mind\n")
    out.append("- Intents monthly volume falling below half its peak for two consecutive quarters, or the on-chain recomputation (L2) disagreeing with DefiLlama by more than its bootstrap interval.\n"
               "- Unique Intents users flat or falling while volume rises (volume concentrated in a handful of market makers; HHI above 0.25 for a quarter).\n"
               "- QAA falling as fast as raw active accounts, which would mean the activity decline is real rather than a bot wash-out.\n"
               "- A positive, stable information coefficient would strengthen the case that the market eventually prices settlement; a persistently negative one would mean Intents growth is a sell signal, not a buy signal.\n"
               "- Any fee-sharing or burn mechanism linking Intents volume to NEAR supply would change the valuation section from scenarios to arithmetic.\n")

    out.append("## Data gaps and integrity\n")
    out.append("- Intents volume: DefiLlama (Dune-sourced). Independent on-chain recomputation: " + (f"computed (L2, source: {is_.get('source')})." if is_.get("computed") else "not computed yet."))
    out.append("- QAA: " + (f"computed (L1, source: {qs.get('source')})." if qs.get("computed") else "not computed yet; no quality adjustment is applied to any number above."))
    out.append("- NEAR Intents Explorer API (1Click transactions) requires a partner JWT; not used.")
    out.append("- NEAR price: NearBlocks daily series; BTC and ETH benchmarks: DefiLlama coins API. CoinGecko's free tier does not serve full history.")
    out.append("- Sampling design, estimators and biases of the no-credentials path: `docs/SAMPLING.md`.")
    out.append("- BigQuery dataset freshness is checked with `sql/q0_freshness.sql` before any L1/L2 run; NEAR Lake was deprecated on 2026-03-24.")
    out.append(f"- Raw snapshot hashes: `docs/REPRODUCIBILITY.md` ({len(raw_manifest())} files).\n")
    out.append("## Reproduce\n")
    out.append("`uv sync --all-extras && make features models charts thesis site` rebuilds this file and the dashboard from `data/`. See README.md.\n")
    return "\n".join(out)


def metrics_doc() -> str:
    rows = [("txns", "NearBlocks", "transactions included per day"), ("active_accounts", "NearBlocks", "distinct accounts that signed a transaction that day"),
            ("new_accounts", "NearBlocks", "accounts created that day"), ("active_contracts", "NearBlocks", "contracts that received a call that day"),
            ("tx_fee_usd / tx_fee_near", "NearBlocks", "gas fees burned, in USD and NEAR"), ("tx_volume_usd", "NearBlocks", "USD value of native NEAR transferred"),
            ("usd_per_txn", "derived", "tx_volume_usd / txns"), ("near_price, market_cap_usd", "NearBlocks", "daily price and market cap"),
            ("intents_volume_usd", "DefiLlama (Dune)", "NEAR Intents swap volume"), ("intents_fees_usd", "DefiLlama", "fees paid on NEAR Intents swaps"),
            ("near_dex_volume_usd", "DefiLlama", "all DEX volume attributed to NEAR, Intents included"), ("near_app_fees_usd", "DefiLlama", "application fees on NEAR (all protocols)"),
            ("tvl_usd", "DefiLlama", "total value locked on NEAR"), ("stablecoins_usd", "DefiLlama", "circulating stablecoin supply on NEAR"),
            ("price_bitcoin, price_ethereum", "DefiLlama coins", "daily benchmark prices"), ("qaa", "BigQuery + clustering", "quality-adjusted active accounts (L1)"),
            ("hhi_solver, top1_solver_share", "BigQuery events", "solver concentration in Intents (L2)")]
    s = "# Metric definitions (generated)\n\n| Column | Source | Definition |\n|---|---|---|\n" + "\n".join(f"| `{a}` | {b} | {c} |" for a, b, c in rows) + "\n"
    return s


def repro_doc() -> str:
    man = raw_manifest()
    s = "# Reproducibility report (generated)\n\nEvery raw snapshot used by the build, with its SHA-256. `make fetch` refreshes them; the build never calls the network.\n\n| File | Fetched at | Bytes | SHA-256 |\n|---|---|---|---|\n"
    s += "\n".join(f"| {r['file']} | {r['fetched_at']} | {r['bytes']:,} | `{r['sha256'][:16]}...` |" for r in man)
    bq = sorted((ROOT / "data" / "bigquery").glob("*.meta.json"))
    if bq:
        s += "\n\n## BigQuery extracts\n\n| SQL | Run at | Rows | GB billed |\n|---|---|---|---|\n"
        for p in bq:
            j = json.loads(p.read_text())
            s += f"| {j['sql']} | {j['run_at']} | {j['rows']:,} | {j['bytes_processed']/1e9:,.1f} |\n"
    return s + "\n"


def run() -> None:
    (ROOT / "THESIS.md").write_text(build())
    (DOCS / "METRICS.md").write_text(metrics_doc())
    (DOCS / "REPRODUCIBILITY.md").write_text(repro_doc())
    print("thesis: THESIS.md, docs/METRICS.md, docs/REPRODUCIBILITY.md written")
